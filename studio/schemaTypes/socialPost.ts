import { defineField, defineType } from "sanity";
import { validateSocialPublication } from "../../shared/social-post.ts";

export const socialPost = defineType({
  name: "socialPost",
  title: "Ausgewählter Social-Beitrag",
  type: "document",
  description: "Manuell ausgewählte Linkkarte. Kein automatischer Feed und kein eingebettetes Plattform-Skript. Nur bestätigte Academy-Beiträge verwenden.",
  initialValue: { displayOrder: 100, visibility: "hidden", contentApproved: false, sourceStatus: "available" },
  fields: [
    defineField({ name: "title", title: "Überschrift", type: "string", validation: R => R.required().min(2).max(120) }),
    defineField({ name: "summary", title: "Kurzer Begleittext", type: "text", rows: 3,
      description: "Eigener, bestätigter Klartext. Keine erfundenen Rückmeldungen, Empfehlungen oder personenbezogenen Angaben. Maximal ein Absatz.",
      validation: R => R.max(700) }),
    defineField({ name: "platform", title: "Plattform", type: "string",
      options: { list: [{ title: "Instagram", value: "instagram" }, { title: "Facebook", value: "facebook" }], layout: "radio" },
      validation: R => R.required() }),
    defineField({ name: "sourceUrl", title: "Direkter Beitragslink", type: "url",
      description: "Instagram: /p/… oder /reel/…; Facebook: /Academy/posts/… oder /reel/…. Keine Kurzlinks oder Login-/Weiterleitungslinks.",
      validation: R => R.required().uri({ scheme: ["https"] }) }),
    defineField({ name: "fallbackUrl", title: "Academy-Profillink als Alternative", type: "url",
      description: "Öffentliches Academy-Profil auf derselben Plattform. Bei nicht verfügbaren Beiträgen erforderlich.",
      validation: R => R.uri({ scheme: ["https"] }) }),
    defineField({ name: "sourceStatus", title: "Beitrag auf der Plattform", type: "string",
      description: "Manuell prüfen. Bei privaten oder gelöschten Beiträgen den Status ändern oder die Karte zurückziehen. Es gibt noch keine automatische Plattformprüfung.",
      options: { list: [{ title: "Verfügbar", value: "available" }, { title: "Nicht verfügbar / privat / gelöscht", value: "unavailable" }], layout: "radio" },
      validation: R => R.required() }),
    defineField({ name: "displayOrder", title: "Reihenfolge", type: "number",
      description: "Kleinere Zahlen zuerst. Die Website zeigt höchstens sechs freigegebene Karten.",
      validation: R => R.required().integer().min(0).max(9999) }),
    defineField({ name: "contentApproved", title: "Beitrag und Wortlaut geprüft", type: "boolean",
      description: "Academy-Zuordnung, öffentlicher Originalbeitrag, Begleittext und erforderliche Rechte sind bestätigt. Keine Einwilligungsdokumente hier speichern." }),
    defineField({ name: "visibility", title: "Website-Freigabe", type: "string",
      options: { list: [{ title: "Zurückhalten", value: "hidden" }, { title: "Auf der Website zeigen", value: "public" }], layout: "radio" },
      description: "Veröffentlichen und die Website erfolgreich neu bauen. Auch zurückgehaltene veröffentlichte Dokumente sind über die öffentliche Sanity-API lesbar.",
      validation: R => R.required() }),
  ],
  validation: R => R.custom(validateSocialPublication).error(),
  orderings: [{ title: "Website-Reihenfolge", name: "displayOrder", by: [{ field: "displayOrder", direction: "asc" }] }],
  preview: {
    select: { title: "title", platform: "platform", visibility: "visibility" },
    prepare: ({ title, platform, visibility }) => ({ title: title || "Neuer Social-Beitrag", subtitle: `${platform || "Plattform wählen"} · ${visibility === "public" ? "Website-Freigabe" : "Zurückgehalten"}` }),
  },
});
